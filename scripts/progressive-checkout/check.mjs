import assert from 'node:assert/strict';
import {CHECKOUT_STEPS,detailsErrors,invalidateFrom,reachable} from '../../src/patterns/progressive-checkout/model.ts';
const all=CHECKOUT_STEPS.map(s=>s.id);
assert.equal(reachable('review','cart',[]),false);
assert.equal(reachable('cart','details',['cart']),true);
assert.equal(reachable('details','details',[]),true);
assert.deepEqual(invalidateFrom(all,'cart'),[]);
assert.deepEqual(invalidateFrom(all,'details'),['cart']);
assert.deepEqual(invalidateFrom(all,'payment'),['cart','details']);
assert.deepEqual(all,['cart','details','payment','review']);
assert.ok(Object.values(detailsErrors({name:'',email:'bad',country:''})).every(Boolean));
assert.ok(Object.values(detailsErrors({name:' Alex ',email:'alex@example.com',country:'Canada'})).every(x=>!x));
assert.ok(detailsErrors({name:'  ',email:'a@b',country:''}).email);
let completed=['cart','details','payment'];
completed=invalidateFrom(completed,'details');
assert.equal(reachable('review','details',completed),false);
assert.equal(reachable('payment','details',completed),false);
assert.equal(reachable('cart','details',completed),true);
console.log('Step reachability, downstream invalidation and detail validation passed.');
