import assert from 'node:assert/strict';
import {emptyRun,handoffReducer as reduce,mentionAt,removeMention,cleanHandoff} from '../../src/components/agent-handoff/model.ts';
const start=(r=emptyRun,fail=false)=>reduce(r,{type:'start',id:'run-1',agentId:'claude',body:'  fix exports  ',fail});
const tick=r=>({type:'tick',id:r.id,attempt:r.attempt});
let r=start();assert.equal(r.request,'fix exports');assert.equal(r.status,'analyzing');
assert.equal(reduce(r,{...tick(r),id:'old'}),r);assert.equal(reduce(r,{...tick(r),attempt:0}),r);
assert.equal(reduce(r,{type:'accept'}),r);
const stale=tick(r);r=reduce(r,{type:'stop'});assert.equal(reduce(r,stale),r);
r=reduce(r,{type:'retry'});assert.equal(r.status,'analyzing');assert.equal(reduce(r,stale),r);
r=reduce(r,tick(r));assert.equal(r.status,'awaiting');assert.equal(reduce(r,{type:'start',id:'new',agentId:'codex',body:'other',fail:false}),r);
assert.throws(()=>reduce(r,{type:'reply',body:'  '}));
r=reduce(r,{type:'reply',body:'  use queue  '});assert.equal(r.messages.at(-1).body,'use queue');assert.equal(r.status,'implementing');
r=reduce(r,tick(r));assert.equal(r.status,'review');r=reduce(r,{type:'revise'});assert.equal(r.status,'awaiting');
r=reduce(r,{type:'reply',body:'also cover queue failures'});r=reduce(r,tick(r));r=reduce(r,{type:'accept'});assert.equal(r.status,'completed');
assert.equal(new Set(r.messages.map(m=>m.id)).size,r.messages.length);
const completedTick=tick(r);r=reduce(r,{type:'reset'});assert.equal(r.status,'idle');assert.equal(reduce(r,completedTick),r);
r=start(r,true);r=reduce(r,tick(r));assert.equal(r.status,'failed');assert.equal(r.request,'fix exports');r=reduce(r,{type:'retry'});r=reduce(r,tick(r));assert.equal(r.status,'awaiting');
for(const text of ['','   ','a'.repeat(2001)])assert.throws(()=>cleanHandoff(text));
assert.equal(cleanHandoff('a'.repeat(2000)).length,2000);
assert.equal(mentionAt('user@example.com',16),null);
const text='Please @Cl keep exports scoped';const range=mentionAt(text,10);assert.deepEqual(range,{start:7,end:10,query:'Cl'});assert.equal(removeMention(text,range),'Please  keep exports scoped');
assert.equal(mentionAt('@',1).query,'');assert.equal(mentionAt('done @Claude now',16),null);
console.log('Handoff checks passed: guarded lifecycle, stale-event cancellation, recovery, review iteration, input limits and caret mention preservation.');
