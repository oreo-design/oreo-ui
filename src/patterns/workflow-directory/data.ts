function runHistory(total: number, seed: number) {
  const weights = Array.from({ length: 7 }, (_, i) => 6 + ((seed + i * 3) % 7));
  const sum = weights.reduce((a, b) => a + b, 0);
  const values = weights.map((w) => Math.floor((total * w) / sum));
  values[6] += total - values.reduce((a, b) => a + b, 0);
  return values;
}
