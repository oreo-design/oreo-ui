import assert from 'node:assert/strict';
import { emptyRecipient, validateRecipient, parsePaymentAmount, recipientDestination, recipientName } from '../../../src/components/recipient/model.ts';
let checks=0; const check=(fn)=>{fn(); checks++};
const base={...emptyRecipient('Sample Studio'),email:'hi@sample.example',street:'1 Demo Street',city:'London',postal:'SW1A 1AA',bank:'Sample Bank',routing:'000000000',account:'00001234'};
check(()=>assert.deepEqual(validateRecipient(base),{}));
check(()=>assert.ok(validateRecipient({...base,name:''}).name));
check(()=>assert.ok(validateRecipient({...base,email:'invalid'}).email));
check(()=>assert.ok(validateRecipient({...base,routing:'12'}).routing));
check(()=>assert.ok(validateRecipient({...base,account:'ab12'}).account));
check(()=>assert.deepEqual(validateRecipient({...base,kind:'individual',name:'',firstName:'Alex',lastName:'Lee'}),{}));
check(()=>assert.ok(validateRecipient({...base,kind:'individual',lastName:''}).lastName));
check(()=>assert.deepEqual(validateRecipient({...base,rail:'swift',routing:'',bic:'DEMODEFF'}),{}));
check(()=>assert.ok(validateRecipient({...base,rail:'swift',bic:'BAD'}).bic));
check(()=>assert.deepEqual(validateRecipient({...base,rail:'sepa',account:'',routing:'',bic:'demodeff',iban:'DE00 0000 0000 0000 0000 00'}),{}));
check(()=>assert.ok(validateRecipient({...base,rail:'sepa',iban:'bad'}).iban));
check(()=>assert.deepEqual(validateRecipient({...base,rail:'usdc',bank:'',routing:'',account:'',wallet:'0x'+'0'.repeat(40)}),{}));
check(()=>assert.ok(validateRecipient({...base,rail:'usdc',wallet:'0x1'}).wallet));
check(()=>assert.equal(recipientDestination(base),'Sample Bank · •••• 1234'));
check(()=>assert.equal(recipientName({...base,kind:'individual',firstName:' Alex ',lastName:' Lee '}),'Alex Lee'));
for(const v of ['','0','-1','1e3','NaN','1,000','1.001','1000000.01','1.','0000000001']) check(()=>assert.equal(parsePaymentAmount(v,'ach'),null));
for(const rail of ['ach','swift','sepa']) check(()=>assert.deepEqual(parsePaymentAmount('001250.10',rail),{units:125010n,normalized:'1250.10'}));
check(()=>assert.deepEqual(parsePaymentAmount('0.000001','usdc'),{units:1n,normalized:'0.000001'}));
check(()=>assert.equal(parsePaymentAmount('0.0000001','usdc'),null));
check(()=>assert.equal(parsePaymentAmount('1000000.000001','usdc'),null));
check(()=>assert.equal(parsePaymentAmount('1000000','usdc').units,1000000000000n));
check(()=>assert.equal(parsePaymentAmount('1250.123456','usdc').units,1250123456n));
console.log(`${checks} recipient and decimal-boundary assertions passed.`);
